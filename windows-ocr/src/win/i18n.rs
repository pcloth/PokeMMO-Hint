pub(super) fn fill(template: &str, pairs: &[(&str, &str)]) -> String {
    let mut text = template.to_owned();
    for (key, value) in pairs {
        text = text.replace(&format!("{{{key}}}"), value);
    }
    text
}

pub(super) fn strings(lang: Language) -> &'static Strings {
    match lang {
        Language::Zh => &ZH,
        Language::En => &EN,
        Language::Ja => &JA,
    }
}

